// ¿Cuando es conveniente utilizar un callback, y cuando es necesario utilizar una promesa?

//Los callbacks se usan para ejecutar una función después de otra en tareas simples, como eventos o temporizadores. 
//Son fáciles de aplicar cuando el flujo del programa es corto y directo.
//En cambio, las promesas se utilizan cuando hay varias operaciones asíncronas o procesos encadenados, 
//ya que permiten un código más ordenado, legible y con mejor manejo de errores.
//Depende del tipo de código que necesitemos por ejemplo callbacks para casos simples y promesas para situaciones más complejas.
